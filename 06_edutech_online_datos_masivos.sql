/* Cursos por area. Esperado: Administracion 7, Ciencias Politicas 7, Finanzas 8, Informatica 8
   Inscripciones por area. Esperado: Administracion 69, Ciencias Politicas 38, Finanzas 76, Informatica 148
   (el area vive en la descripcion del curso: ya no existe CATEGORIA) */
SELECT REPLACE(cu.descripcion, 'Curso de ', '') AS area,
       COUNT(DISTINCT cu.id_curso) AS cursos,
       COUNT(i.id_inscripcion)     AS inscripciones
FROM CURSO cu
JOIN CARGA_ACADEMICA c ON c.id_curso = cu.id_curso
LEFT JOIN INSCRIPCION i ON i.id_carga = c.id_carga
GROUP BY REPLACE(cu.descripcion, 'Curso de ', '')
ORDER BY area;

