JOIN PROYECTO p ON p.id_proyecto = e.id_proyecto
WHERE p.id_curso <> c.id_curso
UNION ALL
SELECT 'beca de un programa distinto al del curso', COUNT(*)
FROM INSCRIPCION i
JOIN BECA b ON b.id_beca = i.id_beca
JOIN CARGA_ACADEMICA c ON c.id_carga = i.id_carga
JOIN CURSO cu ON cu.id_curso = c.id_curso
